#!/usr/bin/env python3
"""Conditional observables of one frozen two-slope ECT-completion background.

The dimensionless background is generated by the declared scalar--tensor
action and supplied initial state.  Each H0 value is an alternative disclosed
dimensional calibration of that same fixed orbit and state, not a replacement background;
it is a mere change of units only if all physical clocks, matter, Planck and
recombination scales are co-rescaled.  The growth and
sound-horizon layers are explicitly conditional approximations with their
extra metric, quasistatic, photon and recombination assumptions recorded in
the output.  Nothing in this script is a unique P1--P6 prediction.
"""

from __future__ import annotations

